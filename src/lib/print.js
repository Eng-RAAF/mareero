import { date, money } from "./format";

const esc = (s) => String(s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

/**
 * Opens a printable document (invoice, quotation, PO, statement…) in a new window.
 * columns: [{ header, value(row), align }]
 */
export function printDocument({ company, title, number, docDate, meta = [], partyTitle, party = [], columns, rows, totals = [], notes }) {
  const w = window.open("", "_blank", "width=900,height=1000");
  if (!w) {
    alert("Allow pop-ups to print.");
    return;
  }
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>${esc(title)} ${esc(number)}</title>
<style>
 *{box-sizing:border-box} body{font-family:Inter,Segoe UI,Arial,sans-serif;color:#1e293b;margin:32px;font-size:13px}
 .top{display:flex;justify-content:space-between;align-items:flex-start;border-bottom:3px solid #039855;padding-bottom:16px}
 .co{font-size:20px;font-weight:700;color:#05603a}.muted{color:#64748b}
 h1{font-size:22px;margin:0;text-transform:uppercase;letter-spacing:1px;text-align:right}
 .grid{display:flex;justify-content:space-between;gap:24px;margin:20px 0}
 .box h3{font-size:11px;text-transform:uppercase;color:#64748b;margin:0 0 4px}
 table{width:100%;border-collapse:collapse;margin-top:8px} th{background:#f1f5f9;text-align:left;font-size:11px;text-transform:uppercase;color:#475569;padding:8px}
 td{padding:8px;border-bottom:1px solid #e2e8f0} .r{text-align:right}
 .totals{margin-left:auto;width:300px;margin-top:12px} .totals div{display:flex;justify-content:space-between;padding:4px 0}
 .totals .grand{border-top:2px solid #1e293b;font-weight:700;font-size:15px;margin-top:4px;padding-top:8px}
 .notes{margin-top:28px;padding:12px;background:#f8fafc;border-radius:6px}
 .foot{margin-top:40px;font-size:11px;color:#94a3b8;text-align:center}
 @media print{body{margin:12mm}}
</style></head><body>
<div class="top"><div><div class="co">${esc(company?.name)}</div>
<div class="muted">${esc(company?.address ?? "")}${company?.phone ? "<br>" + esc(company.phone) : ""}${company?.email ? "<br>" + esc(company.email) : ""}${company?.taxId ? "<br>Tax ID: " + esc(company.taxId) : ""}</div></div>
<div><h1>${esc(title)}</h1><div class="r"><b>${esc(number)}</b><br>${esc(date(docDate))}</div></div></div>
<div class="grid"><div class="box"><h3>${esc(partyTitle ?? "")}</h3>${party.map((p) => `<div>${esc(p)}</div>`).join("")}</div>
<div class="box r">${meta.map(([k, v]) => `<div><span class="muted">${esc(k)}:</span> ${esc(v)}</div>`).join("")}</div></div>
<table><thead><tr>${columns.map((c) => `<th class="${c.align === "right" ? "r" : ""}">${esc(c.header)}</th>`).join("")}</tr></thead>
<tbody>${rows.map((r) => `<tr>${columns.map((c) => `<td class="${c.align === "right" ? "r" : ""}">${esc(c.value(r))}</td>`).join("")}</tr>`).join("")}</tbody></table>
<div class="totals">${totals.map(([k, v, grand]) => `<div class="${grand ? "grand" : ""}"><span>${esc(k)}</span><span>${esc(v)}</span></div>`).join("")}</div>
${notes ? `<div class="notes">${esc(notes)}</div>` : ""}
<div class="foot">Generated by Mareero Auto Spare Parts Management System</div>
<script>window.onload=()=>{window.print()}</script></body></html>`;
  w.document.open();
  w.document.write(html);
  w.document.close();
}

export { money };
